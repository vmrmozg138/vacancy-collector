"""Нормализация названий для сопоставления данных из разных источников.

Задача простая на вид и неприятная на практике: в API вакансий регион называется
«Город Москва» и «Чувашская Республика - Чувашия», а в справочнике — «Москва»
и «Чувашская Республика — Чувашия». Сопоставлять их «в лоб» нельзя, поэтому строится
нормализованный ключ, по которому две записи считаются одним и тем же регионом.

Что делает ключ:

* приводит к нижнему регистру и заменяет «ё» на «е» (иначе «Королёв» и «Королев» — разные);
* выбрасывает содержимое скобок («Саха (Якутия)» и «Саха» — одно и то же);
* убирает служебные слова («город», «республика», «область», «автономный округ»),
  потому что в одном источнике они есть, а в другом нет;
* заменяет дефисы, тире и пунктуацию на пробелы — «Чувашская Республика — Чувашия»
  и «Чувашская Республика - Чувашия» дают одно и то же;
* сортирует оставшиеся слова, чтобы порядок не влиял на результат.

Важно: ключ нужен только для сопоставления. Показываем пользователю всегда исходное
название — «Город Москва» остаётся «Город Москва», ключ «москва» в интерфейс не попадает.
"""

from __future__ import annotations

import re

#: Слова, которые в одних источниках есть, а в других отсутствуют.
SERVICE_WORDS = frozenset(
    {
        "город",
        "г",
        "республика",
        "респ",
        "область",
        "обл",
        "край",
        "автономный",
        "автономная",
        "округ",
        "ао",
    }
)

_PUNCTUATION = re.compile(r"[—–\-\.,;:!?()«»\"'`]")
_PARENTHESES = re.compile(r"\([^)]*\)")
_SPACES = re.compile(r"\s+")


def normalize_name(name: str | None) -> str:
    """Вернуть нормализованный ключ названия (пустая строка, если названия нет)."""
    if not name:
        return ""

    text = name.casefold().replace("ё", "е")
    text = _PARENTHESES.sub(" ", text)
    text = _PUNCTUATION.sub(" ", text)
    tokens = [token for token in _SPACES.sub(" ", text).split() if token and token not in SERVICE_WORDS]

    # dict.fromkeys убирает повторы, сохраняя порядок, sorted делает ключ независимым от порядка слов.
    return " ".join(sorted(dict.fromkeys(tokens)))


def search_key(text: str | None) -> str:
    """Ключ для поиска подстроки без учёта регистра.

    Зачем не обойтись `LIKE`/`ILIKE`: в SQLite функция `lower()` понимает только латиницу
    («Дворник» остаётся «Дворник»), поэтому поиск «программист» находил 63 вакансии из 73 —
    терялись названия с заглавной буквы. Проверено на живой базе 16.10.2026.

    Поэтому ключ считается в Python и хранится в базе рядом с исходным названием:
    нижний регистр, «ё» → «е», схлопнутые пробелы. Показываем пользователю по-прежнему
    исходный текст — ключ живёт только для поиска и сравнения.
    """
    if not text:
        return ""
    return _SPACES.sub(" ", text.casefold().replace("ё", "е")).strip()
