"""Признак удалённой работы.

Отдельного «человеческого» поля «можно удалённо» источник не отдаёт, но у него есть
официальное поле `employment`, где встречается значение «Дистанционная (удаленная) работа».
Это самый надёжный признак — он заполнен работодателем, а не выведен нами.

Второй, слабый признак — упоминание удалёнки в тексте вакансии. Здесь важна деталь:
наивный поиск подстроки «удал» даёт мусор, потому что ловит «удаление» — у дворника
«удаление мусора», у плиточника «удаление старой плитки». Поэтому ищем «удаленн»/«удалённ»
(двойная «н») и «дистанционн»: проверено на 588 реальных вакансиях — грубый поиск давал
39 совпадений вместе с уборщиками, точный даёт только тех, кто правда пишет про удалёнку.

Классификация нужна ещё и потому, что два признака не совпадают: часть вакансий пишет
про удалёнку в обязанностях, но в поле `employment` указана полная занятость.
"""

from __future__ import annotations

#: Значение официального поля `employment`, означающее дистанционную работу.
REMOTE_EMPLOYMENT_MARKER = "Дистанционная (удаленная) работа"

#: Подстроки, по которым удалёнка ищется в тексте вакансии.
#: Двойная «н» — намеренно: одиночное «удал» ловит «удаление».
REMOTE_WORD_MARKERS = (
    "удаленн",
    "Удаленн",
    "удалённ",
    "Удалённ",
    "дистанционн",
    "Дистанционн",
)

#: Все подстроки, по которым вакансия считается «про удалёнку» — для SQL-фильтра.
ALL_REMOTE_MARKERS = (REMOTE_EMPLOYMENT_MARKER, *REMOTE_WORD_MARKERS)

#: Значения классификации.
OFFICIAL = "official"
MENTIONED = "mentioned"


def classify_remote(raw: str | None) -> str | None:
    """Определить вид признака удалёнки по исходному JSON вакансии.

    Возвращает `OFFICIAL` (заполнено официальное поле), `MENTIONED` (удалёнка только
    в тексте) или None. Официальный признак сильнее: если он есть, остальное не важно.
    """
    if not raw:
        return None
    if REMOTE_EMPLOYMENT_MARKER in raw:
        return OFFICIAL
    if any(marker in raw for marker in REMOTE_WORD_MARKERS):
        return MENTIONED
    return None
